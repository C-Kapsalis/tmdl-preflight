_PLAIN_SAFE = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_./ -]*$")


def _yaml_scalar(value: str) -> str:
    """A YAML scalar, quoted when a plain one would be read as something
    else."""
    if not value or not _PLAIN_SAFE.match(value) or value.endswith(" "):
        return "'" + value.replace("'", "''") + "'"
    if value.lower() in {"true", "false", "yes", "no", "on", "off", "null", "~"}:
        return "'" + value + "'"
    if re.fullmatch(r"[-+]?\d+(\.\d+)?", value) or re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        return "'" + value + "'"
    return value


def holdbacks_yaml(entries: list[dict], previous: dict[str, str],
                   today: Optional[str] = None) -> str:
    """The holdbacks file: every client in the entries file, with the work
    that holds its deploy."""
    today = today or _dt.datetime.now(_dt.timezone.utc).date().isoformat()
    by_client: dict[str, list[dict]] = {}
    for e in entries:
        by_client.setdefault(str(e.get("client", "")), []).append({
            "table": str(e.get("table", "")),
            "view": str(e.get("view", "")),
            "columns": [str(c) for c in (e.get("columns") or [])],
        })
    lines = [HOLDBACKS_HEADER.rstrip("\n"), "version: 1"]
    if not by_client:
        lines.append("holdbacks: []")
    else:
        lines.append("holdbacks:")
        for client in sorted(by_client):
            lines.append(f"- client: {_yaml_scalar(client)}")
            since = previous.get(client) or "'" + today + "'"
            lines.append(f"  since: {since}")
            lines.append("  blocking:")
            for b in by_client[client]:
                lines.append(f"  - table: {_yaml_scalar(b['table'])}")
                lines.append(f"    view: {_yaml_scalar(b['view'])}")
                if b["columns"]:
                    lines.append("    columns:")
                    for c in b["columns"]:
                        lines.append(f"    - {_yaml_scalar(c)}")
                else:
                    lines.append("    columns: []")
    return "\n".join(lines) + "\n"


def previous_since(path: Path) -> dict[str, str]:
    """The ``since`` value of each client in a holdbacks file, as it was
    written (a quoted date stays quoted)."""
    if not path.is_file():
        return {}
    out: dict[str, str] = {}
    owner = None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\s*-\s*client:\s*(.+?)\s*$", line)
        if m:
            owner = m.group(1).strip("'\"")
            continue
        m = re.match(r"^\s*since:\s*(.+?)\s*$", line)
        if m and owner:
            out[owner] = m.group(1)
    return out


def git_head(root: Path) -> str:
    """The short commit the SQL project is at, or ``unknown``."""
    try:
        out = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                             capture_output=True, timeout=60, check=True).stdout
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return out.decode("utf-8", "replace").strip() or "unknown"
