"""Prove from SQL view definitions that a model's source views expose the
columns the model needs (``schema-check --sql-dir``). Local files only: the
SQL project is a checkout the user keeps current; nothing connects to a
warehouse."""

from __future__ import annotations

import datetime as _dt
import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Optional

_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
_LINE_COMMENT = re.compile(r"--[^\n]*")
_STAR = re.compile(r"\bselect\s+(?:\w+\s*\.\s*)?\*", re.IGNORECASE)
_SOURCE = re.compile(r"\{\{\s*source\(\s*['\"]([^'\"]+)['\"]\s*,\s*['\"]([^'\"]+)['\"]\s*\)\s*\}\}")
_REF = re.compile(r"\{\{\s*ref\(\s*['\"]([^'\"]+)['\"]\s*\)\s*\}\}")

HOLDBACKS_HEADER = """\
## deploy_holdbacks.yml — clients whose deploy is HELD pending view enrichment.
## AUTO-GENERATED by `tmdl-preflight schema-check --sql-dir ... --write-holdbacks`
## from the outstanding-enrichment entries file — do not
## hand-edit. Entries clear when the SQL-state check turns READY and
## `--clear-ready` removes them from the entries file.
"""


def clean_sql(text: str, strip_blocks: tuple[str, ...] = ("config",)) -> str:
    text = _BLOCK_COMMENT.sub(" ", text)
    text = _LINE_COMMENT.sub(" ", text)
    for name in strip_blocks:
        text = re.sub(r"\{\{\s*" + re.escape(name) + r"\s*\(.*?\)\s*\}\}", " ", text, flags=re.DOTALL)
    return text


def exposes(sql: str, column: str) -> bool:
    c = re.escape(column)
    return bool(re.search(r"`" + c + r"`", sql, re.IGNORECASE)
                or re.search(r'"' + c + r'"', sql, re.IGNORECASE)
                or re.search(r"(?<![\w`])" + c + r"(?![\w`])", sql, re.IGNORECASE))


def has_select_star(sql: str) -> bool:
    """A star select: ``select *`` or ``select <alias> . *``."""
    return _STAR.search(sql) is not None


def from_relations(sql: str) -> list[tuple[str, str]]:
    """``(kind, name)`` for every ``source()``/``ref()`` the model reads; only
    the ones inside jinja braces count."""
    rels = [("source", m.group(2)) for m in _SOURCE.finditer(sql)]
    rels += [("ref", m.group(1)) for m in _REF.finditer(sql)]
    return rels


@dataclass
class Verdict:
    owner: str
    table: str
    view: str
    ready: bool
    reason: str
    missing: list[str]


def _owner_segment(owner: str, pattern: Optional[str]) -> tuple[Optional[str], bool]:
    """``(segment, matched)``: the folder segment that holds the owner's
    views, and whether the client key matched the pattern at all."""
    if not pattern:
        return None, True
    m = re.search(pattern, owner)
    if not m:
        return None, False
    return (m.group(1) if m.groups() else m.group(0)), True


def find_sql(root: Path, view: str, segment: Optional[str]) -> Optional[Path]:
    for p in sorted(root.rglob(f"{view}.sql")):
        if segment is not None and segment not in p.relative_to(root).parts:
            continue
        return p
    return None


def judge(entry: dict, root: Path, pattern: Optional[str] = None,
          strip_blocks: tuple[str, ...] = ("config",)) -> Verdict:
    owner = str(entry.get("client", entry.get("owner", "")))
    table = str(entry.get("table", ""))
    view = str(entry.get("view", ""))
    cols = [str(c) for c in entry.get("columns") or []]
    segment, matched = _owner_segment(owner, pattern)
    if not matched:
        return Verdict(owner, table, view, False, f"cannot derive org id from '{owner}'", cols)
    path = find_sql(root, view, segment)
    if path is None:
        return Verdict(owner, table, view, False,
                       "view not in DBT (repo-stale / hand-made) — import via /enrich-view", cols)
    rel = path.relative_to(root).as_posix()
    sql = clean_sql(path.read_text(encoding="utf-8", errors="replace"), strip_blocks)
    missing = [c for c in cols if not exposes(sql, c)]
    if not missing:
        return Verdict(owner, table, view, True,
                       f"{rel}: every required column exposed explicitly ({len(cols)} col(s))", [])
    if not has_select_star(sql):
        return Verdict(owner, table, view, False,
                       f"{rel}: explicit select list lacks {len(missing)} required column(s): "
                       f"{', '.join(missing)}", missing)
    rels = from_relations(sql)
    shared = str(entry.get("shared_view") or "")
    if shared and any(kind == "source" and ident == shared for kind, ident in rels):
        return Verdict(owner, table, view, True,
                       f"{rel}: SELECT * passes through the ETL-materialized universal source "
                       f"'{shared}' — columns flow with the underlay materialization", [])
    for kind, ident in rels:
        if kind != "ref":
            continue
        hop = find_sql(root, ident, segment)
        if hop is None:
            continue
        hop_sql = clean_sql(hop.read_text(encoding="utf-8", errors="replace"), strip_blocks)
        still = [c for c in missing if not exposes(hop_sql, c)]
        if not still:
            return Verdict(owner, table, view, True,
                           f"{rel}: SELECT * over ref('{ident}') — one-hop trace exposes all "
                           f"required columns", [])
        if has_select_star(hop_sql):
            return Verdict(owner, table, view, False,
                           f"{rel}: SELECT * over ref('{ident}') which is itself SELECT * — beyond "
                           f"the one-hop static trace; verify manually", still)
        missing = still
    others = ", ".join(f"{k}:{i}" for k, i in rels) or "no relation found"
    return Verdict(owner, table, view, False,
                   f"{rel}: SELECT * but not over the universal source '{shared}' ({others}) — "
                   f"missing column(s) not statically provable: {', '.join(missing)}", missing)


def _normalise_entry(entry: dict) -> dict:
    """One entry, in the shape the check reads."""
    e = dict(entry)
    e["view"] = e.get("view") or e.get("client_view") or ""
    e["shared_view"] = e.get("shared_view") or e.get("universal_view") or ""
    e["columns"] = [str(c.get("sourceColumn", "")) if isinstance(c, dict) else str(c)
                    for c in (e.get("columns") or [])]
    return e


def load_registry(path: Path) -> dict:
    """The entries file as it is written; a missing file is an empty
    registry."""
    p = Path(path)
    if not p.is_file():
        return {"schema_version": 1, "entries": []}
    try:
        data = json.loads(p.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise ValueError(f"cannot read the entries file: {exc}") from exc
    if not isinstance(data, dict):
        return {"schema_version": 1, "entries": []}
    return data


def load_entries(path: Path) -> list[dict]:
    data = load_registry(path)
    entries = data.get("entries") if isinstance(data, dict) else data
    if not isinstance(entries, list):
        return []
    return [_normalise_entry(e) for e in entries if isinstance(e, dict)]


def clear_ready(path: Path, data: dict, ready_clients: Iterable[str]) -> int:
    """Remove the entries of the clients whose every entry is READY."""
    ready = {str(c) for c in ready_clients}
    entries = data.get("entries") or []
    kept = [e for e in entries if str(e.get("client")) not in ready]
    removed = len(entries) - len(kept)
    if removed:
        data["entries"] = kept
        Path(path).write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return removed


