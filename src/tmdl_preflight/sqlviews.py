"""Prove from SQL view definitions that a model's source views expose the
columns the model needs (``schema-check --sql-dir``). Local files only: the
SQL project is a checkout the user keeps current; nothing connects to a
warehouse."""

from __future__ import annotations

import datetime as _dt
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.DOTALL)
_LINE_COMMENT = re.compile(r"--[^\n]*")
_STAR = re.compile(r"\bselect\s+(?:distinct\s+)?(?:\w+\.)?\*", re.IGNORECASE)
_SOURCE = re.compile(r"source\(\s*['\"]([^'\"]+)['\"]\s*,\s*['\"]([^'\"]+)['\"]\s*\)")
_REF = re.compile(r"ref\(\s*['\"]([^'\"]+)['\"]\s*\)")


def clean_sql(text: str, strip_blocks: tuple[str, ...] = ("config",)) -> str:
    text = _BLOCK_COMMENT.sub(" ", text)
    text = _LINE_COMMENT.sub(" ", text)
    for name in strip_blocks:
        text = re.sub(r"\{\{\s*" + re.escape(name) + r"\s*\(.*?\)\s*\}\}", " ", text, flags=re.DOTALL)
    return text


def exposes(sql: str, column: str) -> bool:
    c = re.escape(column)
    return bool(re.search(r"`" + c + r"`", sql, re.IGNORECASE)
                or re.search(r'"' + c + r'"', sql, re.IGNORECASE)
                or re.search(r"(?<![\w`])" + c + r"(?![\w`])", sql, re.IGNORECASE))


@dataclass
class Verdict:
    owner: str
    table: str
    view: str
    ready: bool
    reason: str
    missing: list[str]


def _owner_segment(owner: str, pattern: Optional[str]) -> Optional[str]:
    if not pattern:
        return None
    m = re.search(pattern, owner)
    return (m.group(1) if m and m.groups() else (m.group(0) if m else owner))


def find_sql(root: Path, view: str, owner: str, pattern: Optional[str]) -> Optional[Path]:
    seg = _owner_segment(owner, pattern)
    for p in sorted(root.rglob(f"{view}.sql")):
        if seg is not None and seg not in p.relative_to(root).parts:
            continue
        return p
    return None


def judge(entry: dict, root: Path, pattern: Optional[str] = None,
          strip_blocks: tuple[str, ...] = ("config",)) -> Verdict:
    owner, table, view = str(entry.get("client", entry.get("owner", ""))), str(entry.get("table", "")), str(entry.get("view", ""))
    cols = [str(c) for c in entry.get("columns") or []]
    path = find_sql(root, view, owner, pattern)
    if path is None:
        return Verdict(owner, table, view, False, "view definition not found in the SQL directory", cols)
    sql = clean_sql(path.read_text(encoding="utf-8", errors="replace"), strip_blocks)
    missing = [c for c in cols if not exposes(sql, c)]
    if not missing:
        return Verdict(owner, table, view, True, f"exposed explicitly ({len(cols)} column(s))", [])
    if not _STAR.search(sql):
        return Verdict(owner, table, view, False, f"not exposed: {', '.join(missing)}", missing)
    shared = entry.get("shared_view")
    sources = _SOURCE.findall(sql)
    if shared and any(name == shared for _schema, name in sources):
        return Verdict(owner, table, view, True, f"SELECT * over the shared view {shared}", [])
    refs = _REF.findall(sql)
    for ref in refs:
        rpath = find_sql(root, ref, owner, pattern)
        if rpath is None:
            continue
        rsql = clean_sql(rpath.read_text(encoding="utf-8", errors="replace"), strip_blocks)
        missing = [c for c in missing if not exposes(rsql, c)]
        if not missing:
            return Verdict(owner, table, view, True, f"one-hop trace through {ref}", [])
        if _STAR.search(rsql):
            return Verdict(owner, table, view, False,
                           f"{ref} also selects *: beyond the one-hop trace; verify manually "
                           f"({', '.join(missing)})", missing)
    seen = [f"source({s}, {n})" for s, n in sources] + [f"ref({r})" for r in refs]
    return Verdict(owner, table, view, False,
                   f"SELECT * over {', '.join(seen) or 'no relation found'}; could not prove "
                   f"{', '.join(missing)}", missing)


def load_entries(path: Path) -> list[dict]:
    data = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    entries = data.get("entries") if isinstance(data, dict) else data
    if not isinstance(entries, list):
        raise ValueError("the entries file needs an 'entries' list")
    return [e for e in entries if isinstance(e, dict)]


def holdbacks_yaml(verdicts: list[Verdict], entries: list[dict], previous: dict[str, str],
                   today: Optional[str] = None) -> str:
    today = today or _dt.datetime.now(_dt.timezone.utc).date().isoformat()
    held: dict[str, list[dict]] = {}
    for v in verdicts:
        if not v.ready:
            held.setdefault(v.owner, []).append({"table": v.table, "view": v.view, "columns": v.missing})
    lines = ["# Generated by tmdl-preflight schema-check --write-holdbacks; do not edit by hand.",
             "version: 1", "holdbacks:" + ("" if held else " []")]
    for owner in sorted(held):
        lines.append(f"  - client: {json.dumps(owner)}")
        lines.append(f"    since: {json.dumps(previous.get(owner, today))}")
        lines.append("    blocking:")
        for b in held[owner]:
            lines.append(f"      - table: {json.dumps(b['table'])}")
            lines.append(f"        view: {json.dumps(b['view'])}")
            lines.append(f"        columns: {json.dumps(b['columns'])}")
    return "\n".join(lines) + "\n"


def previous_since(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    out, owner = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r'^\s*-\s*client:\s*"?([^"]+)"?\s*$', line)
        if m:
            owner = m.group(1)
            continue
        m = re.match(r'^\s*since:\s*"?([^"]+)"?\s*$', line)
        if m and owner:
            out[owner] = m.group(1)
    return out
