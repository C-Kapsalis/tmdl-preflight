"""The generated rule catalog page (``rules --format markdown``).

The page is deterministic: rules sorted by id, no timestamps, one trailing
newline. ``rules --format markdown --out FILE --check`` compares the file
byte for byte with a fresh render, so a committed catalog cannot go stale
without a red check.
"""

from __future__ import annotations

from .rules.base import RuleSet

REGENERATE = "tmdl-preflight rules --format markdown --out {out}"
_RULE_CHARS = set("═=-─")


def cell(text: str) -> str:
    """Escape a table cell: ``|`` becomes ``\\|``, newlines become spaces."""
    return " ".join(text.replace("|", "\\|").split("\n")).strip()


def summary_line(text: str) -> str:
    """First non-empty line that is not made only of rule characters."""
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and not set(stripped) <= _RULE_CHARS:
            return stripped
    return ""


def render_markdown_catalog(ruleset: RuleSet, out: str = "docs/rules.md") -> str:
    rules = sorted(ruleset.rules, key=lambda r: r.id)
    fixable = [r for r in rules if r.fixable]
    baselinable = [r for r in rules if r.baselinable]
    lines = [
        "<!-- Generated by tmdl-preflight; do not edit by hand.",
        f"     Regenerate with: {REGENERATE.format(out=out)} -->",
        "",
        "# tmdl-preflight rule catalog",
        "",
        f"Rules: **{len(rules)}** · auto-fixable: **{len(fixable)}** · "
        f"baselinable: **{len(baselinable)}**.",
        "",
        "| Rule | Name | Severity | Fix | Description |",
        "|---|---|---|---|---|",
    ]
    for r in rules:
        desc = cell(summary_line(r.description)) or "—"
        lines.append(
            f"| {r.id} | {cell(r.name)} | {r.severity.value} | "
            f"{'yes' if r.fixable else 'no'} | {desc} |"
        )
    lines += [
        "",
        "## Auto-fixable rules",
        "",
        "Run `tmdl-preflight fix <path>` to repair these; a fixer marked "
        "unsafe runs only when its rule is selected explicitly.",
        "",
        "| Rule | Name | Safe in a blanket fix |",
        "|---|---|---|",
    ]
    for r in fixable:
        lines.append(f"| {r.id} | {cell(r.name)} | {'yes' if r.safe else 'no'} |")
    return "\n".join(lines).rstrip("\n") + "\n"
